  }

  Future<void> generateSOSMessage() async {
    try {
      Position position = await Geolocator.getCurrentPosition(
        desiredAccuracy: LocationAccuracy.high,
      );
      List<Placemark> placemarks = await placemarkFromCoordinates(
        position.latitude,
        position.longitude,
      );

      Placemark place = placemarks.first;

      String address =
          "${place.street},\n"
          "${place.locality},\n"
          "${place.administrativeArea},\n"
          "${place.country}";

      setState(() {
        gpsReady = true;
      });

      String currentDate = DateFormat('dd MMM yyyy').format(DateTime.now());

      String currentTime = DateFormat('hh:mm a').format(DateTime.now());

      String message =
          "🚨 EMERGENCY ALERT 🚨\n\n"
          "I need immediate assistance.\n\n"
          "📅 Date : $currentDate\n"
          "🕒 Time : $currentTime\n\n"
          "📍 Address :\n"
          "$address\n\n"
          "🗺 Google Maps :\n"
          "https://maps.google.com/?q=${position.latitude},${position.longitude}\n\n"
          "Generated by SafeSphere AI";
      setState(() {
        sosMessage = message;
      });

      ScaffoldMessenger.of(
        context,
      ).showSnackBar(const SnackBar(content: Text("SOS Message Generated")));
    } catch (e) {
      print(e);
    }
  }

  Future<void> startSOSCountdown() async {
    setState(() {
      isCounting = true;
      cancelSOS = false;
      countdown = 3;
    });

    while (countdown > 0) {
      await Future.delayed(const Duration(seconds: 1));

      if (!mounted) return;

      if (cancelSOS) {
        setState(() {
          isCounting = false;
          countdown = 3;
        });

        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(
            content: Text("❌ SOS Cancelled"),
            backgroundColor: Colors.orange,
          ),
        );

        return;
      }

      setState(() {
        countdown--;
      });
    }

    setState(() {
      isCounting = false;
    });

    await generateSOSMessage();
    await playSiren();
    await vibratePhone();

    ScaffoldMessenger.of(context).showSnackBar(
      const SnackBar(
        content: Text("🚨 SOS ACTIVATED"),
        backgroundColor: Colors.red,
      ),
    );
  }

  Future<void> copyMessage() async {
    await Clipboard.setData(ClipboardData(text: sosMessage));

